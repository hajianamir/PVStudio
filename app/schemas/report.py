"""
Report Configuration & White-Label Schemas
Decouples Report Section Toggles from White-Label Branding Config
Per Technical Specification §5.3 & Sprint 5 Planning
"""

from typing import Dict, List, Optional
from pydantic import BaseModel, Field


class BrandingConfig(BaseModel):
    company_name: str = Field(default="PVStudio Engineering", description="Installer or enterprise company name")
    logo_url: Optional[str] = Field(default=None, description="URL or base64 image string for corporate logo")
    primary_color_hex: str = Field(default="#3B82F6", description="Primary brand accent color")
    footer_disclaimer_text: Optional[str] = Field(
        default="Generated by PVStudio. Subject to final professional engineer verification.",
        description="Custom report footer legal disclaimer"
    )


class SectionToggles(BaseModel):
    include_executive_summary: bool = True
    include_3d_roof_layout: bool = True
    include_system_bill_of_materials: bool = True
    include_electrical_sld: bool = True
    include_financial_cashflow: bool = True
    include_compliance_checklist: bool = True


class ReportConfig(BaseModel):
    report_title: str = Field(default="Solar PV Proposal & Design Package")
    template_type: str = Field(default="RESIDENTIAL_PROPOSAL", description="RESIDENTIAL_PROPOSAL or PERMIT_PACKAGE")
    section_toggles: SectionToggles = Field(default_factory=SectionToggles)
    branding_config: BrandingConfig = Field(default_factory=BrandingConfig)
